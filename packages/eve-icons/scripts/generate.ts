/**
 * Generate `src/generated/` — one React component per icon — from
 * `manifest.json` and `assets/`.
 *
 *   pnpm --filter @jitaspace/eve-icons kubb:generate
 *
 * Offline and deterministic, so it runs on install and ahead of every
 * build, type-check, lint and test (it is wired to the `kubb:generate` task
 * name, as `@jitaspace/esi-metadata` does with its own codegen). Each icon's
 * PNGs are inlined as data URIs, so the package works with any bundler and
 * a consumer only ships the icons it imports. Text metadata is stripped from
 * the inlined copies (see `stripMetadata`); `assets/` keeps the originals.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import type { Manifest } from "./manifest";
import { stripMetadata } from "./png";
import { componentName, ICON_SETS, label, LEGACY_NAMES } from "./sets";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src", "generated");
const iconsDir = join(outDir, "icons");

const HEADER =
  "// Generated by scripts/generate.ts from manifest.json and assets/ — do not edit.\n" +
  "// The artwork is © CCP hf. (Fenris Creations), not MIT-licensed: see LICENSE.\n";

function main() {
  const manifest = JSON.parse(
    readFileSync(join(root, "manifest.json"), "utf8"),
  ) as Manifest;
  const sets = new Map(ICON_SETS.map((set) => [set.id, set]));

  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(iconsDir, { recursive: true });

  const components = new Map<string, string>(); // component → icon ID
  const byId = new Map<string, string>(); // icon ID → component
  const metadata: string[] = [];

  for (const icon of manifest.icons) {
    const set = sets.get(icon.set);
    if (!set) throw new Error(`${icon.id}: unknown set "${icon.set}"`);
    const component = componentName(set, icon.name);
    const clash = components.get(component);
    if (clash) {
      throw new Error(`${icon.id} and ${clash} both map to ${component}`);
    }
    components.set(component, icon.id);
    byId.set(icon.id, component);

    const sources = icon.files.map((file) => {
      const base64 = Buffer.from(
        stripMetadata(readFileSync(join(root, "assets", file.file))),
      ).toString("base64");
      return `    { width: ${file.width}, height: ${file.height}, src: "data:image/png;base64,${base64}" },`;
    });
    writeFileSync(
      join(iconsDir, `${component}.ts`),
      `${HEADER}import { createEveIcon } from "../../createEveIcon";

/**
 * \`${icon.id}\`: ${icon.files.map((file) => `${file.width}px`).join(", ")}.
 *
 * From \`${icon.files.map((file) => file.source).join("`, `")}\`.
 */
export const ${component} = /* @__PURE__ */ createEveIcon({
  id: ${JSON.stringify(icon.id)},
  label: ${JSON.stringify(label(icon.name))},
  monochrome: ${icon.monochrome},
  sources: [
${sources.join("\n")}
  ],
});
`,
    );
    metadata.push(
      `  { id: ${JSON.stringify(icon.id)}, set: ${JSON.stringify(icon.set)}, component: ${JSON.stringify(component)}, monochrome: ${icon.monochrome}, sizes: [${icon.files.map((file) => file.width).join(", ")}] },`,
    );
  }

  const aliases: string[] = [];
  for (const [alias, id] of Object.entries(LEGACY_NAMES)) {
    const component = byId.get(id);
    if (!component) {
      throw new Error(`Legacy name ${alias} points at missing icon ${id}`);
    }
    if (components.has(alias)) {
      throw new Error(`Legacy name ${alias} clashes with a generated icon`);
    }
    aliases.push(
      `export { ${component} as ${alias} } from "./icons/${component}";`,
    );
  }

  writeFileSync(
    join(outDir, "index.ts"),
    `${HEADER}${[...components.keys()]
      .map(
        (component) => `export { ${component} } from "./icons/${component}";`,
      )
      .join("\n")}

// Names from before the package was generated, kept so existing imports work.
${aliases.sort().join("\n")}
`,
  );

  writeFileSync(
    join(outDir, "metadata.ts"),
    `${HEADER}
/** Every icon ID in the package. */
export type EveIconId =
${manifest.icons.map((icon) => `  | ${JSON.stringify(icon.id)}`).join("\n")};

export interface EveIconMetadata {
  id: EveIconId;
  set: string;
  /** Name of the exported component. */
  component: string;
  /** Whether the icon can be tinted with the \`color\` prop. */
  monochrome: boolean;
  /** Native widths, in pixels, smallest first. */
  sizes: readonly number[];
}

/** The client build the icons were taken from. */
export const EVE_ICONS_BUILD = ${JSON.stringify(manifest.build)};

/** One entry per icon, without the artwork, for listing and search. */
export const EVE_ICONS: readonly EveIconMetadata[] = [
${metadata.join("\n")}
];

/** The icon sets, in display order. */
export const EVE_ICON_SETS = ${JSON.stringify(
      ICON_SETS.map(({ id, label: setLabel, description }) => ({
        id,
        label: setLabel,
        description,
      })),
      null,
      2,
    )} as const;
`,
  );

  console.log(
    `Generated ${components.size} icons and ${aliases.length} legacy aliases from build ${manifest.build}`,
  );
}

main();
